-- ============================================================================
-- DB 계정 비밀번호 교체 — public 저장소에 노출된 값 무효화
--
--   대상 DB   : sjlab (개발 = 운영 동일 인스턴스)
--   실행 계정 : superuser (자기 비밀번호를 바꾸는 것이므로 본인 계정으로도 가능)
--   작성      : 2026-11-16
--   성격      : **DCL(ALTER ROLE)**. 에이전트가 임의로 실행하지 않는다.
--
-- ----------------------------------------------------------------------------
-- 왜 필요한가
-- ----------------------------------------------------------------------------
-- 이 계정의 주소·아이디·비밀번호가 **public 저장소 3곳**에 평문으로 커밋돼 있었다.
--
--     sj-lab-scheduler   (2025-08-01 부터)
--     mapservice-rest
--     sj-qfieldsync      (QFieldCloud admin 비밀번호도 같은 값을 재사용)
--
-- 게다가 접속 주소가 클러스터 내부 이름이 아니라 **공인 IP + NodePort** 라
-- 주소와 비밀번호를 아는 누구나 바깥에서 붙을 수 있었다. 계정은 표 소유자(superuser) 다.
--
-- 2026-11-16 에 세 저장소의 코드·차트를 Secret 방식으로 바꿨지만, **git 이력에는 과거 값이
-- 그대로 남는다.** 과거 커밋에서 읽히므로 **비밀번호를 바꾸지 않으면 아무것도 해결되지 않는다.**
-- (이력 재작성은 이미 퍼진 클론·포크에 효과가 없고 위험해 택하지 않았다.)
--
-- ----------------------------------------------------------------------------
-- 순서를 지킬 것 — 세 서비스가 이 계정을 공유한다
-- ----------------------------------------------------------------------------
--   ❶ 세 서비스가 **Secret 에서 접속 정보를 읽도록 배포된 뒤에** 이 스크립트를 돌린다.
--     (그전에 바꾸면 지도·수집·동기화가 한꺼번에 멈춘다 — 운영 지도 화면이 전부 500 이 된다)
--   ❷ 이 스크립트 실행
--   ❸ 로컬 비밀값 파일의 접속 문자열을 새 비밀번호로 고친다
--   ❹ scripts\create-service-secrets.ps1 을 다시 돌린다(Secret 갱신 + 파드 재시작)
--   ❺ kubectl get pods -n sj-lab 으로 세 파드 확인 · 지도 화면과 /estate/status 확인
--
-- 자세한 절차와 포털 키 재발급은 docs/k8s-secrets.md 의 "비밀값 교체" 절 참고.
--
-- ----------------------------------------------------------------------------
-- 새 비밀번호 만들기
-- ----------------------------------------------------------------------------
-- · 32자 이상, 영문 대소문자·숫자·기호를 섞는다.
-- · **다른 곳에서 쓰는 비밀번호를 재사용하지 말 것** — 이번 사고의 원인 중 하나가
--   QFieldCloud admin 과 DB 가 같은 비밀번호를 쓴 것이었다.
-- · `@` `:` `/` `#` `?` 가 들어가면 접속 문자열(postgresql://...)에서 URL 인코딩해야 한다
--   (`@` → `%40`). 번거로우면 그 문자들을 피하는 쪽이 편하다.
-- · 만든 값은 **로컬 비밀값 파일과 k8s Secret 에만** 둔다. 이 파일이나 history 에 적지 말 것.
--
-- 예: PowerShell 로 안전한 값 만들기(화면에 한 번만 보인다)
--   -join ((48..57) + (65..90) + (97..122) + @(45,46,95) | Get-Random -Count 40 | % { [char]$_ })
--
-- ----------------------------------------------------------------------------
-- 되돌리기
-- ----------------------------------------------------------------------------
-- 같은 문장으로 옛 비밀번호를 다시 넣으면 되돌아간다. 다만 **옛 값은 공개돼 있으므로
-- 되돌리지 말 것.** 접속이 안 되면 비밀번호를 되돌리는 대신 Secret·로컬 파일을 고친다.
-- ============================================================================


-- ============================================================================
-- ❶ 실행 전 확인 — 지금 붙어 있는 세션을 본다 (조회만)
-- ============================================================================
-- 비밀번호를 바꿔도 **이미 붙어 있는 연결은 끊기지 않는다**(다음 재접속부터 적용).
-- 그래서 파드를 재시작해야 새 값으로 붙는다.
SELECT usename AS 계정,
       count(*) AS 연결수,
       min(backend_start)::timestamp(0) AS 가장_오래된_연결
FROM pg_stat_activity
WHERE datname = current_database()
GROUP BY usename
ORDER BY 연결수 DESC;


-- ============================================================================
-- ❷ 비밀번호 교체
-- ============================================================================
-- 아래 한 줄에서 계정 이름과 새 비밀번호를 채워 실행한다.
--
--   · 계정 이름은 로컬 비밀값 파일의 접속 문자열에 들어 있는 그 계정이다.
--   · psql 로 돌릴 때는 **명령 기록에 남지 않도록** 주의한다.
--     파일로 실행하거나(`psql -f`), 세션에서 한 번만 입력할 것.
--
-- ALTER ROLE "<계정이름>" WITH PASSWORD '<새 비밀번호>';


-- ============================================================================
-- ❸ 실행 후 확인
-- ============================================================================
-- (1) 바뀐 시각 확인 — 방금이면 적용된 것이다
SELECT rolname AS 계정, rolsuper AS superuser여부, rolvaliduntil AS 만료일
FROM pg_roles
WHERE rolcanlogin
ORDER BY rolname;

-- (2) 새 비밀번호로 붙는지 확인 (셸에서)
--   psql "postgresql://<계정>:<새 비밀번호>@<호스트>:<포트>/sjlab" -c "select 1"
--
-- (3) 파드 재시작 후 세 서비스 확인 (셸에서)
--   kubectl get pods -n sj-lab
--   curl -s https://api.sj-lab.co.kr/estate/status
--   지도 화면: https://sj-lab.co.kr/map/


