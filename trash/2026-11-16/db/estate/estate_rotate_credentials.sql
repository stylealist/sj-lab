-- (나) **DB 의 공인 노출 줄이기.** 지금은 NodePort 로 바깥에서 붙을 수 있다. 파드는
--      클러스터 서비스 이름으로 붙으면 되므로, 외부 접근은 필요한 IP 로 제한하거나
--      닫는 것이 맞다. 로컬 개발·MCP 조회가 그 경로를 쓰고 있어 대체 방법
--      (포트 포워딩 등)을 함께 정해야 한다.
