-- ============================================================================
-- PostgreSQL WAL·체크포인트 설정 — 대량 적재가 디스크를 70% 체크포인트에 쓰는 문제
--
--   대상 DB   : sjlab (개발 = 운영 동일 인스턴스)
--   실행 계정 : stylealist (superuser — ALTER SYSTEM 에 필요)
--   작성      : 2026-11-13
--   성격      : **서버 설정 변경(ALTER SYSTEM)**. 에이전트가 임의로 실행하지 않는다.
--               두 값 모두 **재시작이 필요 없다**(`pg_reload_conf()` 로 즉시 적용).
--
-- ----------------------------------------------------------------------------
-- 무엇을 보고 이 결론에 왔나 (2026-11-13 실측)
-- ----------------------------------------------------------------------------
-- 전월세 보증금 복구(한 달에 5~8만 행 적재 + 같은 수만큼 삭제)가 **한 달 1.5분 → 13분**으로
-- 느려졌다. 하루 전에도 같은 일이 있었고, DB 를 재시작하면 다시 빨라졌다가 약 300만 행을
-- 넣은 시점에서 또 꺾였다. 디스크·죽은자리·인덱스를 의심했지만 모두 아니었다
-- (`VACUUM` 으로 죽은 자리 197만 개를 0 으로 만들어도 12분 → 11분).
--
-- 체크포인트 통계가 원인을 바로 보여 줬다(가동 1시간 16분 기준).
--
--     정상(시간) 체크포인트    4 회
--     강제 체크포인트         37 회     ← 2분마다
--     체크포인트 쓰기 시간  3,162 초     ← 가동 시간의 70%
--
-- `강제 체크포인트` 는 WAL 공간(`max_wal_size`)이 꽉 차서 **어쩔 수 없이** 하는 것이다.
-- 체크포인트 직후에는 모든 변경 페이지가 **통째로(full page image)** WAL 에 다시 기록되므로,
-- 체크포인트가 잦으면 쓰기량이 몇 배로 불어난다. 즉 **디스크가 느린 것이 아니라
-- 디스크를 체크포인트에 쓰고 있었다.**
--
--     max_wal_size      1024MB  ← 기본값. 이 작업의 쓰기량에 비해 너무 작다
--     wal_compression   off     ← 그 full page image 를 압축 없이 그대로 쓴다
--     checkpoint_timeout 300s
--     shared_buffers    128MB   ← 작지만 이건 재시작이 필요하다(아래 참고)
--
-- ----------------------------------------------------------------------------
-- 바꾸는 것 (둘 다 재시작 없이 적용)
-- ----------------------------------------------------------------------------
-- 1) wal_compression = on
--    full page image 를 압축한다. **디스크를 더 쓰지 않고 오히려 줄인다** — 위험이 없다.
--    CPU 를 조금 더 쓰지만 이 서버는 CPU 가 남는다(VACUUM 측정에서 CPU 5.5초 / 809초).
--
-- 2) max_wal_size = 3GB  (1GB → 3GB)
--    WAL 이 덜 자주 차서 강제 체크포인트가 크게 줄어든다.
--    **대가: WAL 파일이 최대 약 3GB 까지 늘어난다**(DB 본체 9.7GB 와 별도).
--    디스크 여유가 적으면 이 값을 올리지 말 것 — WAL 이 디스크를 채우면 **DB 가 멈춘다.**
--    여유가 넉넉하면 8GB 까지 올리는 것이 더 효과적이다.
--
-- ----------------------------------------------------------------------------
-- 되돌리기
-- ----------------------------------------------------------------------------
-- 맨 아래 "되돌리기" 블록 두 줄을 실행하면 즉시 원래대로 돌아간다(재시작 불필요).
-- ============================================================================


-- ============================================================================
-- ❶ 실행 전 확인 — 지금 상태를 먼저 본다 (조회만)
-- ============================================================================
SELECT name, setting, unit, context
FROM pg_settings
WHERE name IN ('max_wal_size','min_wal_size','wal_compression','checkpoint_timeout',
               'checkpoint_completion_target','shared_buffers')
ORDER BY name;

-- 체크포인트가 실제로 폭주하는지 — num_requested 가 num_timed 보다 훨씬 크면 그렇다
SELECT num_timed      AS 정상_체크포인트,
       num_requested  AS 강제_체크포인트,
       round(write_time / 1000.0)                       AS 쓰기_초,
       round(extract(epoch FROM now() - pg_postmaster_start_time())) AS 가동_초,
       round(100.0 * (write_time / 1000.0)
             / extract(epoch FROM now() - pg_postmaster_start_time()), 1) AS 쓰기_비율_pct
FROM pg_stat_checkpointer;

-- **WAL 디렉터리가 쓰는 디스크의 여유를 먼저 확인할 것** (아래는 superuser 만 보인다)
-- SELECT pg_size_pretty(sum(size)) AS wal_now, count(*) AS files FROM pg_ls_waldir();


-- ============================================================================
-- ❷ 적용 (superuser)
-- ============================================================================
ALTER SYSTEM SET wal_compression = 'on';
ALTER SYSTEM SET max_wal_size = '3GB';

SELECT pg_reload_conf();

-- 적용됐는지 확인 — 둘 다 재시작 없이 바로 바뀐다
SELECT name, setting, unit FROM pg_settings
WHERE name IN ('wal_compression','max_wal_size');


